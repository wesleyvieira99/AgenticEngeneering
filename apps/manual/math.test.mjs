import assert from 'node:assert/strict';
import { vectorMetrics, softmax, attention, tokenEstimate, contextBudget, costEstimate, concurrency, gradient } from './math.mjs';
const near = (x, y) => assert.ok(Math.abs(x-y)<1e-9, `${x} != ${y}`);
near(vectorMetrics([1,0],[1,1]).cosine, Math.SQRT1_2);
assert.equal(vectorMetrics([0,0],[1,1]).cosine, null);
assert.throws(()=>vectorMetrics([1],[1,2]));
assert.throws(()=>vectorMetrics([NaN],[1]));
near(softmax([1000,1001]).reduce((a,b)=>a+b),1);
assert.throws(()=>softmax([-Infinity]));
assert.throws(()=>softmax([1],0));
const mask=attention([1,0],[[1,0],[0,1]],[[2,0],[999,999]],true);
assert.deepEqual(mask.output,[2,0]);
assert.deepEqual(mask.weights,[1,0]);
const a=attention([1,0],[[1,0],[0,1]],[[2,0],[0,4]]);
near(a.weights[0],0.6697615493266569);
assert.equal(tokenEstimate('ação').bytes,6);
assert.equal(tokenEstimate('ação').characters,4);
assert.equal(contextBudget(100,[50,60]).overflow,10);
near(costEstimate(1000,100,2,8,10,20).total,0.0336);
assert.equal(concurrency(10,2,100).total,500);
assert.equal(concurrency(3,10,100).total,100);
near(gradient(1,.1)[1].loss,.16);
assert.ok(gradient(1,.4,3)[3].loss>4);
console.log('20+ numerical/edge checks passed; educational formulas only, no provider validation.');
